#: 支持的 scope。**顺序即 `--help` 的顺序**。
SCOPES = ('fast', 'block', 'etf', 'etc', 'etc_1', 'etc_2')


def etf_scope_codes() -> list:
    """`etf` scope 的码表（排序后的列表）。**纯函数**。

    >>> codes = etf_scope_codes()
    >>> len(codes)
    506
    >>> '510300' in codes, '399001' in codes      # 混着真指数（见模块 docstring）
    (True, True)
    >>> '159531' in codes                         # 旧树的语法疣把它吃掉了
    False
    """
    return sorted(_ETF_LEGACY)


def focus_block_codes(verbose: bool = True, echo=None) -> list:
    """`focus_block` 的成分股（**去重、6 位、排序**）。

    板块表读 8.3 的 ``golemq_stock_cn.stock_block``；点名却不在表里的板块**打印一行**
    （照旧树），因为它们「在通达信板块分类中已被移除」。
    """
    from .refdata import GQ_fetch_stock_block
    from .symbol import focus_block

    df = GQ_fetch_stock_block(blocknames=focus_block)
    if df is None or len(df) == 0:
        return []
    have = set(df.index.get_level_values('blockname'))
    missing = sorted(set(focus_block) - have)
    if missing and verbose:
        (echo or print)(f'系统预设的A股板块: {missing} 在通达信板块分类中已被移除')
    return sorted({str(c)[:6] for c in df.index.get_level_values('code')})


def perpar_symbol_range(eval_range='', verbose: bool = True, echo=None):
    """`--eval <scope>` → 代码列表；**解析不出来返回 `False`**（沿用旧树约定）。

    :param eval_range: :data:`SCOPES` 之一（大小写不敏感）。
    :returns: ``list[str]``（升序、去重、6 位）或 ``False``。
    """
    from .refdata import GQ_fetch_stock_list

    say = echo or print
    rng = str(eval_range or '').strip().lower()
    if rng not in SCOPES:
        say(f'[scopes] 未知 scope {eval_range!r}；可用: {SCOPES}')
        return False

    if rng == 'etf':
        codes = list(_ETF_LEGACY)
    elif rng in ('fast', 'block'):
        codes = focus_block_codes(verbose=verbose, echo=say)
    else:                                   # etc / etc_1 / etc_2
        df = GQ_fetch_stock_list()
        all_codes = [] if df is None or len(df) == 0 else [str(c)[:6] for c in df['code']]
        if not all_codes:
            say('[scopes] stock_list 为空 —— 先跑一次 `--save tdx` 灌参考数据')
            return False
        codes = sorted(set(all_codes) - set(focus_block_codes(verbose=verbose, echo=say)))
        if rng in ('etc_1', 'etc_2') and len(codes) > 1700:
            want = 1 if rng == 'etc_1' else 0
            codes = [c for c in codes if (int(c[4]) + int(c[5])) % 2 == want]

    codes = sorted(set(codes))
    if not codes:
        # ⚠️ 旧代码在这里会让 scan **静默什么都不做**（CLI 只判 `is False`）。
        say(f'[scopes] scope {rng!r} 解析出**空清单** —— 一个都不会扫。'
            f'（板块名对不上时，先看 8.3 的 stock_block 是怎么命名的）')
        return False
    if verbose:
        say(f'[scopes] {rng}: {len(codes)} 只')
    return codes
